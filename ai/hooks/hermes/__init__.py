"""ai-core Hermes plugin: the same routing.json as the Claude/Codex hooks.

Installed by ai/adapters/hermes.sh as ~hermes/.hermes/plugins/ai-core (a copy; ai-sync refreshes it).
Files next to this one: plugin.yaml (source), and generated by ai-render: router.py, hooklib.py,
routing.json, L0.md (the hermes user cannot read the owner's home, so the plugin carries copies).

Hooks (interface from the Hermes hooks docs, "Plugin Hooks"):
  register_system_prompt_section  L1: short routing table (max 4,000 chars, cache-safe, once per session)
  pre_llm_call                    L3 regex + L2 forced-eval text, appended to the user message
  pre_tool_call                   L4 gates on shell commands: deny -> {"action": "block"},
                                  ask -> {"action": "approve"} (Hermes human-approval gate)
UNVERIFIED (no Hermes source at hand): the plugin.yaml keys, and the shell tool name/arg key
("terminal" with args.command per the docs example; other names below are guesses).
Every callback catches its own errors, logs them, and returns None (fail open, like the other hooks).
"""
import logging
import os
import sys

HERE = os.path.dirname(os.path.realpath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

log = logging.getLogger("ai-core")
SHELL_TOOLS = {"terminal", "shell", "bash", "run_command", "execute_command", "exec_command"}
SECTION_ID = "ai-core.routing"
SECTION_MAX = 4000


def register(ctx):
    ctx.register_system_prompt_section(SECTION_ID, routing_section, position="after_memory", max_chars=SECTION_MAX)
    ctx.register_hook("pre_llm_call", on_pre_llm_call)
    ctx.register_hook("pre_tool_call", on_pre_tool_call)


# ---------------------------------------------------------------- callbacks

def routing_section(session_info=None):
    """L1: one line per rule (id: action), cut to the 4,000-char section cap. Full L0 is in SOUL.md."""
    try:
        router = load_router()
        routing = router.load_routing()
        lines = ["ai-core routing (full table and tie-breaks: root rules in SOUL.md). Use the named tool first:"]
        for rule in routing.get("rules", []):
            if rule.get("scope") == "opt-in" or rule.get("when") == "session_start":
                continue
            lines.append("- %s: %s" % (rule["id"], rule["action"]))
        text = "\n".join(lines)
        return text if len(text) <= SECTION_MAX else text[:SECTION_MAX - 4].rsplit("\n", 1)[0] + "\n..."
    except Exception as exc:
        log.warning("ai-core routing_section failed: %s", exc)
        return ""


def on_pre_llm_call(session_id="", user_message="", is_first_turn=False, platform="", **kwargs):
    try:
        prompt = message_text(user_message)
        if not prompt.strip():
            return None
        router = load_router()
        payload = {"prompt": prompt, "session_id": "hermes-%s" % session_id, "cwd": kwargs.get("cwd") or os.getcwd()}
        ctx = router.Ctx("hermes", "UserPromptSubmit", payload, "")
        router.on_user_prompt(ctx)
        save(ctx)
        return {"context": "\n\n".join(ctx.contexts)} if ctx.contexts else None
    except Exception as exc:
        log.warning("ai-core pre_llm_call failed: %s", exc)
        return None


def on_pre_tool_call(tool_name="", args=None, task_id="", **kwargs):
    try:
        if tool_name not in SHELL_TOOLS:
            return None
        args = args if isinstance(args, dict) else {}
        cmd = args.get("command") or args.get("cmd") or args.get("script") or ""
        if isinstance(cmd, list):
            cmd = " ".join(str(c) for c in cmd)
        if not cmd:
            return None
        router = load_router()
        payload = {"tool_name": "Bash", "tool_input": {"command": cmd}, "session_id": "hermes-%s" % task_id,
                   "cwd": args.get("cwd") or args.get("workdir") or kwargs.get("cwd") or os.getcwd()}
        ctx = router.Ctx("hermes", "PreToolUse", payload, "")
        router.on_pre_tool(ctx)
        save(ctx)
        reason = "\n".join(ctx.reasons)
        if ctx.decision == "deny":
            return {"action": "block", "message": reason}
        if ctx.decision == "ask":
            return {"action": "approve", "message": reason, "rule_key": "ai-core:gate"}
        return None
    except Exception as exc:
        log.warning("ai-core pre_tool_call failed: %s", exc)
        return None


# ---------------------------------------------------------------- helpers

def load_router():
    import router  # generated copy next to this file (ai-render)
    router.ROUTING_OVERRIDE = os.path.join(HERE, "routing.json")   # never the env: no side effect on tools
    return router


def message_text(msg):
    if isinstance(msg, str):
        return msg
    if isinstance(msg, list):
        return " ".join(p.get("text", "") for p in msg if isinstance(p, dict) and p.get("type") == "text")
    return ""


def save(ctx):
    try:
        if ctx._state is not None:
            ctx._state.save()
    except Exception as exc:
        log.warning("ai-core state save failed: %s", exc)
